    def _add(self, entries):
        """批量添加条目"""
        self.entries.extend(entries)

    def get_topics(self):
        """获取所有话题"""
        topics = set()
        for entry in self.entries:
            for t in entry.get('topics', []):
                topics.add(t)
        return list(topics)

    def get_entries_for_topic(self, topic):
        """获取某个话题下的所有条目"""
        return [e for e in self.entries if topic in e.get('topics', [])]
