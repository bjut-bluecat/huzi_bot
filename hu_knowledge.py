class HuKnowledge:
    """户晨风知识库 - 结构化管理户子的所有观点"""

    def __init__(self):
        self.entries = []
        self._build_knowledge_base()

    def query(self, question: str, topics: List[str] = None) -> Optional[Dict]:
        """
        根据问题匹配知识库条目
        返回最佳匹配的条目，包含 position, reasoning, style_markers
        """
        if not self.entries:
            return None

        question = question.strip()
        q_words = set(jieba.cut(question))
        q_lower = question.lower()

        best_entry = None
        best_score = 0

        for entry in self.entries:
            score = self._score_entry(entry, question, q_words, q_lower, topics)
            if score > best_score:
                best_score = score
                best_entry = entry

        if best_score >= 3.0:
            return {
                'entry': best_entry,
                'score': best_score,
                'response': self._compose_response(best_entry, question),
            }
        return None

    def _score_entry(self, entry, question, q_words, q_lower, topics):
        """计算问题与知识条目的匹配分数"""
        score = 0.0

        # 1. 关键词匹配（最重要）
        for kw in entry['keywords']:
            if kw in question:
                score += 3.0
                # 长关键词额外加分
                if len(kw) >= 3:
                    score += 1.0

        # 2. 分词重叠
        entry_words = set(jieba.cut(' '.join(entry['keywords'])))
        overlap = q_words & entry_words
        score += len(overlap) * 0.5

        # 3. 话题匹配
        if topics:
            for t in entry.get('topics', []):
                if t in topics:
                    score += 2.0

        # 4. 问题类型匹配
        if 'question_types' in entry:
            for qt in entry['question_types']:
                if re.search(qt, question):
                    score += 2.0
                    break

        # 5. 否定条件检查
        if 'negate_if' in entry:
            for neg in entry['negate_if']:
                if neg in question:
                    score -= 5.0

        return score

    def _compose_response(self, entry, question):
        """从知识条目生成回答"""
        import random
        # 从该条目的多个回复中随机选一个
        response = random.choice(entry['responses'])
        return response

